let LANG = 'zh-CN';

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]);
  if (s == null) s = I18N['zh-CN'][key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}

// 根据浏览器语言猜一个默认界面语言
function detectLang() {
  const nav = (navigator.language || '').toLowerCase();
  if (nav.startsWith('zh')) return /tw|hk|mo|hant/.test(nav) ? 'zh-TW' : 'zh-CN';
  if (nav.startsWith('ja')) return 'ja';
  if (nav.startsWith('en')) return 'en';
  return 'zh-CN';
}

function setLang(lang) {
  LANG = LANGS[lang] ? lang : 'zh-CN';
  document.documentElement.lang = LANG;
  document.title = t('app.title');
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
}

// 判断一段 System Prompt 是否是某种语言的默认内容（没被用户改过）
function isDefaultSystemPrompt(text) {
  return Object.keys(I18N).some((l) => I18N[l].defaultSystemPrompt === text);
}
