// 上次显示的界面语言另外同步存一份在 localStorage：设置存在 IndexedDB 里，要等异步读取完才知道，
// 页面一载入就先换成上次的语言，不会先闪一下 index.html 里写的简体中文。读取设置后仍以设置为准
const LANG_CACHE_KEY = 'proteus.lang';
function cachedLang() {
  try {
    const v = localStorage.getItem(LANG_CACHE_KEY);
    return LANGS[v] ? v : null;
  } catch (_) {
    return null; // 存储不可用（例如被浏览器禁用）时按系统语言
  }
}
function forgetCachedLang() {
  try { localStorage.removeItem(LANG_CACHE_KEY); } catch (_) { /* 存储不可用 */ }
}

let LANG = cachedLang() || detectLang(); // 读取设置之前（例如本机数据读取失败时的提示）先用上次的语言，没有就按系统语言

function t(key, vars) {
  let s = (I18N[LANG] && I18N[LANG][key]);
  if (s == null) s = I18N['zh-CN'][key];
  if (s == null) return key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? String(vars[k]) : m));
  return s;
}

// 还没在设置里选过界面语言时，按系统语言自动选择：
//   - Windows / macOS / Linux 原生应用：主进程通过网址参数 syslang 传入操作系统的首选语言
//   - 安卓版、网页版：系统 WebView / 浏览器的首选语言
// 不是支持的四种语言之一时用英语
function detectLang() {
  const sys = new URLSearchParams(location.search).get('syslang');
  return matchLang(sys || (navigator.languages && navigator.languages[0]) || navigator.language || '');
}

// 语言标签（例如 zh-Hans-CN、zh-TW、ja-JP、de-DE）对应到界面语言
function matchLang(tag) {
  const l = String(tag).toLowerCase().replace(/_/g, '-');
  if (l === 'zh' || l.startsWith('zh-')) {
    if (/(^|-)hans(-|$)/.test(l)) return 'zh-CN';
    return /(^|-)(hant|tw|hk|mo)(-|$)/.test(l) ? 'zh-TW' : 'zh-CN';
  }
  if (l === 'ja' || l.startsWith('ja-')) return 'ja';
  return 'en';
}

// 运行在原生应用里（电脑版 Electron、安卓版 Capacitor），还是浏览器里（网页版）
const IN_NATIVE_APP = /\bElectron\//.test(navigator.userAgent)
  || !!(window.Capacitor && window.Capacitor.isNativePlatform && window.Capacitor.isNativePlatform());

// 「清除软件数据」确认弹窗里的变量：{webMark} / {nativeMark} 在网页版 / 原生应用那一边标上「（本软件）」，另一边为空
function pageVars() {
  const mark = t('set.currentApp');
  return { webMark: IN_NATIVE_APP ? '' : mark, nativeMark: IN_NATIVE_APP ? mark : '' };
}

function setLang(lang) {
  LANG = LANGS[lang] ? lang : detectLang();
  try { localStorage.setItem(LANG_CACHE_KEY, LANG); } catch (_) { /* 存储不可用：下次载入时按系统语言 */ }
  document.documentElement.lang = LANG;
  document.title = t('app.title');
  for (const el of document.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of document.querySelectorAll('[data-i18n-ph]')) el.placeholder = t(el.dataset.i18nPh);
  for (const el of document.querySelectorAll('[data-i18n-title]')) el.title = t(el.dataset.i18nTitle);
  for (const el of document.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}

